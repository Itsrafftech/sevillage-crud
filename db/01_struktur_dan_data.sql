-- 2a. Reservasi: hanya untuk tamu penginapan, jumlah tamu <= kapasitas,
--     tidak bentrok dengan reservasi aktif lain, dan status berurutan.
CREATE FUNCTION fn_cek_reservasi() RETURNS trigger AS $$
DECLARE
    v_kapasitas SMALLINT;
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pelanggan
                   WHERE id_pelanggan = NEW.id_pelanggan AND is_tamu_penginapan) THEN
        RAISE EXCEPTION 'Pelanggan % bukan tamu penginapan', NEW.id_pelanggan;
    END IF;

    SELECT kapasitas INTO v_kapasitas
    FROM tipe_penginapan WHERE id_layanan = NEW.id_layanan;
    IF NEW.jumlah_tamu > v_kapasitas THEN
        RAISE EXCEPTION 'Jumlah tamu (%) melebihi kapasitas unit (%)',
            NEW.jumlah_tamu, v_kapasitas;
    END IF;

    IF NEW.status_reservasi IN ('Dipesan','Dibayar','Check-in') AND EXISTS (
        SELECT 1 FROM reservasi_penginapan r
        WHERE r.id_layanan = NEW.id_layanan
          AND r.no_unit = NEW.no_unit
          AND r.id_reservasi <> NEW.id_reservasi
          AND r.status_reservasi IN ('Dipesan','Dibayar','Check-in')
          AND r.tgl_check_in < NEW.tgl_check_out
          AND NEW.tgl_check_in < r.tgl_check_out) THEN
        RAISE EXCEPTION 'Unit % nomor % sudah dipesan pada rentang tanggal tersebut',
            NEW.id_layanan, NEW.no_unit;
    END IF;

    IF TG_OP = 'UPDATE' AND NEW.status_reservasi <> OLD.status_reservasi AND NOT (
           (OLD.status_reservasi = 'Dipesan'  AND NEW.status_reservasi IN ('Dibayar','Dibatalkan'))
        OR (OLD.status_reservasi = 'Dibayar'  AND NEW.status_reservasi IN ('Check-in','Dibatalkan'))
        OR (OLD.status_reservasi = 'Check-in' AND NEW.status_reservasi = 'Selesai')) THEN
        RAISE EXCEPTION 'Perubahan status % -> % tidak diizinkan',
            OLD.status_reservasi, NEW.status_reservasi;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_cek_reservasi
BEFORE INSERT OR UPDATE ON reservasi_penginapan
FOR EACH ROW EXECUTE FUNCTION fn_cek_reservasi();

-- 2b. Tarif: periode untuk layanan dan jenis hari yang sama tidak boleh
--     tumpang tindih, dan tarif Weekend tidak lebih rendah dari Weekday.
CREATE FUNCTION fn_cek_tarif() RETURNS trigger AS $$
DECLARE
    v_baru daterange := daterange(NEW.berlaku_mulai, NEW.berlaku_sampai, '[]');
BEGIN
    IF EXISTS (
        SELECT 1 FROM tarif t
        WHERE t.id_layanan = NEW.id_layanan
          AND t.jenis_hari = NEW.jenis_hari
          AND (TG_OP = 'INSERT'
               OR (t.id_layanan, t.jenis_hari, t.berlaku_mulai)
                  IS DISTINCT FROM (OLD.id_layanan, OLD.jenis_hari, OLD.berlaku_mulai))
          AND daterange(t.berlaku_mulai, t.berlaku_sampai, '[]') && v_baru) THEN
        RAISE EXCEPTION 'Periode tarif % (%) tumpang tindih dengan periode lain',
            NEW.id_layanan, NEW.jenis_hari;
    END IF;

    IF EXISTS (
        SELECT 1 FROM tarif t
        WHERE t.id_layanan = NEW.id_layanan
          AND t.jenis_hari <> NEW.jenis_hari
          AND daterange(t.berlaku_mulai, t.berlaku_sampai, '[]') && v_baru
          AND ((NEW.jenis_hari = 'Weekend' AND NEW.harga < t.harga)
            OR (NEW.jenis_hari = 'Weekday' AND NEW.harga > t.harga))) THEN
        RAISE EXCEPTION 'Tarif Weekend tidak boleh lebih rendah dari tarif Weekday (layanan %)',
            NEW.id_layanan;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_cek_tarif
BEFORE INSERT OR UPDATE ON tarif
FOR EACH ROW EXECUTE FUNCTION fn_cek_tarif();

-- 2c. Pemesanan melalui Tiket.com hanya untuk layanan penginapan.
CREATE FUNCTION fn_cek_kanal_detail() RETURNS trigger AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM transaksi t, layanan l
               WHERE t.id_transaksi = NEW.id_transaksi
                 AND l.id_layanan = NEW.id_layanan
                 AND t.kanal_pemesanan = 'Tiket.com'
                 AND l.jenis_layanan <> 'Penginapan') THEN
        RAISE EXCEPTION 'Kanal Tiket.com hanya untuk layanan penginapan (layanan %)',
            NEW.id_layanan;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_cek_kanal_detail
BEFORE INSERT OR UPDATE ON detail_transaksi
FOR EACH ROW EXECUTE FUNCTION fn_cek_kanal_detail();

