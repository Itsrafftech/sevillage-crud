-- ---------------------------------------------------------------------
-- 1. CREATE TABLE
-- Urutan pembuatan mengikuti ketergantungan FK: tabel induk lebih dulu.
-- Seluruh nominal uang memakai INTEGER (rupiah tanpa desimal).
-- ---------------------------------------------------------------------

CREATE TABLE departemen (
    id_departemen    VARCHAR(10)  PRIMARY KEY,               -- contoh: DEP-01
    nama_departemen  VARCHAR(50)  NOT NULL UNIQUE
);

CREATE TABLE jabatan (
    id_jabatan         VARCHAR(10) PRIMARY KEY,               -- contoh: JBT-01
    nama_jabatan       VARCHAR(50) NOT NULL UNIQUE,
    tingkatan_jabatan  SMALLINT    NOT NULL
        CHECK (tingkatan_jabatan BETWEEN 1 AND 5)             -- 1 = tertinggi
);

CREATE TABLE karyawan (
    id_karyawan    VARCHAR(10)  PRIMARY KEY,                  -- contoh: K-001
    id_departemen  VARCHAR(10)  NOT NULL
        REFERENCES departemen (id_departemen) ON DELETE NO ACTION,
    id_jabatan     VARCHAR(10)  NOT NULL
        REFERENCES jabatan (id_jabatan) ON DELETE NO ACTION,
    id_atasan      VARCHAR(10)
        REFERENCES karyawan (id_karyawan) ON DELETE SET NULL,  -- relasi rekursif
    nama           VARCHAR(100) NOT NULL,
    alamat         VARCHAR(150),
    job_desk       VARCHAR(200),
    gaji           INTEGER      NOT NULL CHECK (gaji > 0),
    tunjangan      INTEGER      NOT NULL DEFAULT 0 CHECK (tunjangan >= 0),
    no_bpjs        CHAR(13)     UNIQUE,                       -- 13 digit
    no_rekening    VARCHAR(20)  UNIQUE,
    CONSTRAINT chk_bukan_atasan_sendiri CHECK (id_atasan <> id_karyawan)
);

CREATE TABLE pelanggan (
    id_pelanggan        VARCHAR(10)  PRIMARY KEY,             -- contoh: P-001
    nama                VARCHAR(100),
    no_telepon          VARCHAR(15),
    is_grup             BOOLEAN      NOT NULL DEFAULT FALSE,
    is_tamu_penginapan  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_ots              BOOLEAN      NOT NULL DEFAULT FALSE,
    nama_rombongan      VARCHAR(100),
    alamat              VARCHAR(150),
    -- {Mandatory}: setiap pelanggan memiliki minimal satu peran
    CONSTRAINT chk_minimal_satu_peran
        CHECK (is_grup OR is_tamu_penginapan OR is_ots),
    CONSTRAINT chk_nama_wajib_kecuali_ots   CHECK (is_ots OR nama IS NOT NULL),
    CONSTRAINT chk_grup_punya_rombongan
        CHECK (NOT is_grup OR nama_rombongan IS NOT NULL),
    CONSTRAINT chk_tamu_punya_telepon
        CHECK (NOT is_tamu_penginapan OR no_telepon IS NOT NULL)
);

CREATE TABLE layanan (
    id_layanan     VARCHAR(10)  PRIMARY KEY,                  -- contoh: L-001
    nama_layanan   VARCHAR(60)  NOT NULL UNIQUE,
    jenis_layanan  VARCHAR(15)  NOT NULL
        CHECK (jenis_layanan IN ('Tiket Masuk','Wahana','Paket','Penginapan','Lainnya')),
    status_aktif   BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE tiket_masuk (
    id_layanan           VARCHAR(10) PRIMARY KEY
        REFERENCES layanan (id_layanan) ON DELETE CASCADE,
    kategori_pengunjung  VARCHAR(10) NOT NULL
        CHECK (kategori_pengunjung IN ('Dewasa','Anak','WNA')),
    usia_min             SMALLINT    CHECK (usia_min >= 0),
    usia_maks            SMALLINT,
    CONSTRAINT chk_rentang_usia
        CHECK (usia_maks IS NULL OR usia_min IS NULL OR usia_maks >= usia_min),
    CONSTRAINT chk_usia_anak
        CHECK (kategori_pengunjung <> 'Anak' OR (usia_min = 4 AND usia_maks = 10))
);

CREATE TABLE wahana (
    id_layanan          VARCHAR(10) PRIMARY KEY
        REFERENCES layanan (id_layanan) ON DELETE CASCADE,
    berat_maks          SMALLINT    CHECK (berat_maks > 0),   -- kg; NULL = tanpa batas
    tinggi_min          SMALLINT    CHECK (tinggi_min > 0),   -- cm; NULL = tanpa batas
    status_operasional  VARCHAR(12) NOT NULL DEFAULT 'Beroperasi'
        CHECK (status_operasional IN ('Beroperasi','Perawatan','Ditutup'))
);

CREATE TABLE paket (
    id_layanan      VARCHAR(10) PRIMARY KEY
        REFERENCES layanan (id_layanan) ON DELETE CASCADE,
    kategori_paket  VARCHAR(20) NOT NULL
        CHECK (kategori_paket IN ('Pelajar','Gathering','Fun Games','Edukasi Anak')),
    min_pax         SMALLINT    NOT NULL DEFAULT 20 CHECK (min_pax >= 20),
    jumlah_wahana   SMALLINT    NOT NULL DEFAULT 3 CHECK (jumlah_wahana >= 0)
);

CREATE TABLE tipe_penginapan (
    id_layanan  VARCHAR(10)  PRIMARY KEY
        REFERENCES layanan (id_layanan) ON DELETE CASCADE,
    kapasitas   SMALLINT     NOT NULL CHECK (kapasitas > 0),  -- orang
    luas        NUMERIC(5,1) CHECK (luas > 0)                 -- m2; NULL = belum diketahui
);

CREATE TABLE fasilitas_tipe (
    id_layanan  VARCHAR(10) NOT NULL
        REFERENCES tipe_penginapan (id_layanan) ON DELETE CASCADE,
    fasilitas   VARCHAR(50) NOT NULL,
    PRIMARY KEY (id_layanan, fasilitas)
);

CREATE TABLE tarif (
    id_layanan      VARCHAR(10) NOT NULL
        REFERENCES layanan (id_layanan) ON DELETE CASCADE,
    jenis_hari      VARCHAR(7)  NOT NULL CHECK (jenis_hari IN ('Weekday','Weekend')),
    berlaku_mulai   DATE        NOT NULL,
    berlaku_sampai  DATE,                                     -- NULL = masih berlaku
    harga           INTEGER     NOT NULL CHECK (harga >= 0),
    PRIMARY KEY (id_layanan, jenis_hari, berlaku_mulai),
    CONSTRAINT chk_periode_tarif
        CHECK (berlaku_sampai IS NULL OR berlaku_sampai >= berlaku_mulai)
);

CREATE TABLE unit_penginapan (
    id_layanan   VARCHAR(10) NOT NULL
        REFERENCES tipe_penginapan (id_layanan) ON DELETE CASCADE,
    no_unit      SMALLINT    NOT NULL CHECK (no_unit > 0),
    status_unit  VARCHAR(10) NOT NULL DEFAULT 'Tersedia'
        CHECK (status_unit IN ('Tersedia','Terisi','Perawatan')),
    PRIMARY KEY (id_layanan, no_unit)
);

CREATE TABLE paket_wahana (
    id_paket   VARCHAR(10) NOT NULL REFERENCES paket (id_layanan)  ON DELETE CASCADE,
    id_wahana  VARCHAR(10) NOT NULL REFERENCES wahana (id_layanan) ON DELETE CASCADE,
    PRIMARY KEY (id_paket, id_wahana)
);

CREATE TABLE penugasan_wahana (
    id_karyawan  VARCHAR(10) NOT NULL REFERENCES karyawan (id_karyawan) ON DELETE CASCADE,
    id_layanan   VARCHAR(10) NOT NULL REFERENCES wahana (id_layanan)    ON DELETE CASCADE,
    tgl_tugas    DATE        NOT NULL,
    PRIMARY KEY (id_karyawan, id_layanan, tgl_tugas)
);

CREATE TABLE transaksi (
    id_transaksi     VARCHAR(10) PRIMARY KEY,                 -- contoh: T-001
    id_pelanggan     VARCHAR(10) NOT NULL
        REFERENCES pelanggan (id_pelanggan) ON DELETE NO ACTION,
    id_karyawan      VARCHAR(10) NOT NULL
        REFERENCES karyawan (id_karyawan) ON DELETE NO ACTION,
    waktu_transaksi  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    kanal_pemesanan  VARCHAR(10) NOT NULL DEFAULT 'Loket'
        CHECK (kanal_pemesanan IN ('Loket','WhatsApp','Tiket.com')),
    metode_bayar     VARCHAR(10) NOT NULL
        CHECK (metode_bayar IN ('Tunai','Transfer','Debit'))   -- QRIS tidak diterima
);

CREATE TABLE detail_transaksi (
    id_transaksi  VARCHAR(10) NOT NULL
        REFERENCES transaksi (id_transaksi) ON DELETE CASCADE,
    no_urut       SMALLINT    NOT NULL CHECK (no_urut >= 1),
    id_layanan    VARCHAR(10) NOT NULL
        REFERENCES layanan (id_layanan) ON DELETE NO ACTION,
    jumlah        SMALLINT    NOT NULL DEFAULT 1 CHECK (jumlah >= 1),
    harga_satuan  INTEGER     NOT NULL CHECK (harga_satuan >= 0),  -- salinan harga saat transaksi
    PRIMARY KEY (id_transaksi, no_urut)
);

CREATE TABLE tiket (
    no_tiket       VARCHAR(12) PRIMARY KEY,                   -- contoh: TK-0001
    id_transaksi   VARCHAR(10) NOT NULL,
    no_urut        SMALLINT    NOT NULL,
    tgl_kunjungan  DATE        NOT NULL,
    status_tiket   VARCHAR(10) NOT NULL DEFAULT 'Aktif'
        CHECK (status_tiket IN ('Aktif','Terpakai','Dibatalkan')),
    FOREIGN KEY (id_transaksi, no_urut)                        -- FK komposit
        REFERENCES detail_transaksi (id_transaksi, no_urut) ON DELETE NO ACTION
);

CREATE TABLE reservasi_penginapan (
    id_reservasi      VARCHAR(10) PRIMARY KEY,                -- contoh: R-001
    id_pelanggan      VARCHAR(10) NOT NULL
        REFERENCES pelanggan (id_pelanggan) ON DELETE NO ACTION,
    id_layanan        VARCHAR(10) NOT NULL,
    no_unit           SMALLINT    NOT NULL,
    id_karyawan       VARCHAR(10) NOT NULL
        REFERENCES karyawan (id_karyawan) ON DELETE NO ACTION,
    id_transaksi      VARCHAR(10) UNIQUE                       -- relasi melunasi 1:1
        REFERENCES transaksi (id_transaksi) ON DELETE SET NULL,
    tgl_pesan         DATE        NOT NULL DEFAULT CURRENT_DATE,
    tgl_check_in      DATE        NOT NULL,
    tgl_check_out     DATE        NOT NULL,
    jumlah_tamu       SMALLINT    NOT NULL CHECK (jumlah_tamu >= 1),
    jenis_kendaraan   VARCHAR(20),
    kanal_pemesanan   VARCHAR(10) NOT NULL
        CHECK (kanal_pemesanan IN ('Loket','WhatsApp','Tiket.com')),
    status_reservasi  VARCHAR(10) NOT NULL DEFAULT 'Dipesan'
        CHECK (status_reservasi IN ('Dipesan','Dibayar','Check-in','Selesai','Dibatalkan')),
    FOREIGN KEY (id_layanan, no_unit)                          -- FK komposit
        REFERENCES unit_penginapan (id_layanan, no_unit) ON DELETE NO ACTION,
    CONSTRAINT chk_urutan_tanggal_inap CHECK (tgl_check_out > tgl_check_in),
    CONSTRAINT chk_pesan_sebelum_inap  CHECK (tgl_pesan <= tgl_check_in),
    CONSTRAINT chk_dibayar_punya_transaksi
        CHECK (status_reservasi IN ('Dipesan','Dibatalkan') OR id_transaksi IS NOT NULL)
);

