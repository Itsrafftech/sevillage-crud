-- ---------------------------------------------------------------------
-- 4. VIEW
-- Atribut turunan (total_bayar, subtotal, lama_menginap) tidak disimpan;
-- nilainya dihitung lewat view. v_karyawan_umum menyembunyikan data gaji,
-- tunjangan, BPJS, dan rekening untuk pengguna selain HRD dan Finance.
-- ---------------------------------------------------------------------
CREATE VIEW v_detail_transaksi AS
SELECT d.*, d.jumlah * d.harga_satuan AS subtotal
FROM detail_transaksi d;

CREATE VIEW v_transaksi AS
SELECT t.id_transaksi, t.waktu_transaksi, t.id_pelanggan, t.id_karyawan,
       t.kanal_pemesanan, t.metode_bayar,
       SUM(d.jumlah * d.harga_satuan) AS total_bayar
FROM transaksi t
JOIN detail_transaksi d ON d.id_transaksi = t.id_transaksi
GROUP BY t.id_transaksi;

CREATE VIEW v_reservasi AS
SELECT r.*, r.tgl_check_out - r.tgl_check_in AS lama_menginap
FROM reservasi_penginapan r;

CREATE VIEW v_karyawan_umum AS
SELECT id_karyawan, nama, id_departemen, id_jabatan, id_atasan, job_desk
FROM karyawan;
